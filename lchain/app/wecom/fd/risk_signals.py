def signals_for(risk: str) -> list[str]:
    """返回该风险对应的危险信号（未命中返回空列表，由调用方兜底）。"""
    text = (risk or "").strip()
    if not text:
        return []
    out: list[str] = []
    for pattern, signals in _RULES:
        if re.search(pattern, text):
            for s in signals:
                if s not in out:
                    out.append(s)
    return out


def rule_count() -> int:
    return len(_RULES)
